from app.brands import merge

STRENGTH = {"follow": 2, "ignore": 1, "default": 0}


def apply(conn) -> None:
    def brand_of(spelling):
        row = conn.execute("SELECT brand_id FROM brand_aliases WHERE alias = ?", (spelling,)).fetchone()
        return row["brand_id"] if row else None

    for name, spellings in MERGES.items():
        ids = list(dict.fromkeys(i for i in map(brand_of, spellings) if i is not None))
        if not ids:
            continue
        statuses = [conn.execute("SELECT status FROM brands WHERE id = ?", (i,)).fetchone()["status"] for i in ids]
        for other in ids[1:]:
            merge(conn, other, ids[0])
        conn.execute("UPDATE brands SET name = ?, status = ? WHERE id = ?",
                     (name, max(statuses, key=STRENGTH.get), ids[0]))
    for spelling, name in RENAMES.items():
        # Only while the brand still has the supplier's name, so a name you chose stays.
        conn.execute("""UPDATE brands SET name = ? WHERE name = ?
                        AND id = (SELECT brand_id FROM brand_aliases WHERE alias = ?)""", (name, spelling, spelling))
